/* Tornanti storefront. No build step, no framework: reads data/rides.json
   (generated by scripts/tracks/build_tracks.py) and store.json (prices and
   Gumroad links, edited by hand), then draws the catalog, the maps and the
   elevation profiles. */
(function () {
  "use strict";

  const body = document.body;
  const BASE = body.dataset.base || "./";
  const PAGE = body.dataset.page;
  const SVG_NS = "http://www.w3.org/2000/svg";
  const C = { route: "#c0392b", sky: "#3d8fc4", ink: "#231f16", paper: "#faf6ec", line: "#ddd3bd" };

  const euro = new Intl.NumberFormat("it-IT", { style: "currency", currency: "EUR" });
  const num = (v, d = 0) => v.toLocaleString("it-IT", { minimumFractionDigits: d, maximumFractionDigits: d });
  const km = (v) => `${num(v, v < 100 ? 1 : 0)} km`;
  const metres = (v) => `${num(v)} m`;
  const duration = (min) => {
    const h = Math.floor(min / 60), m = min % 60;
    return h ? `${h} h${m ? ` ${m} min` : ""}` : `${m} min`;
  };

  function el(tag, attrs = {}, ...children) {
    const node = tag.startsWith("svg:") ? document.createElementNS(SVG_NS, tag.slice(4)) : document.createElement(tag);
    for (const [k, v] of Object.entries(attrs)) {
      if (v === null || v === undefined || v === false) continue;
      if (k === "text") node.textContent = v;
      else if (k === "html") node.innerHTML = v;
      else if (k.startsWith("on")) node.addEventListener(k.slice(2), v);
      else node.setAttribute(k, v === true ? "" : v);
    }
    for (const c of children.flat()) if (c != null) node.append(c);
    return node;
  }

  async function load() {
    const [store, data] = await Promise.all([
      fetch(`${BASE}store.json`).then((r) => r.json()),
      fetch(`${BASE}data/rides.json`).then((r) => r.json()),
    ]);
    const rides = data.rides;
    const bySlug = Object.fromEntries(rides.map((r) => [r.slug, r]));
    return { store, rides, bySlug };
  }

  // --- products -------------------------------------------------------------

  function product(store, slug) {
    return store.products[slug] || { price: null, checkout: "" };
  }

  function checkoutUrl(raw) {
    // ?wanted=true takes the buyer straight to Gumroad's checkout.
    if (!raw) return "";
    const u = new URL(raw);
    if (u.hostname.endsWith("gumroad.com")) u.searchParams.set("wanted", "true");
    return u.toString();
  }

  function buyButton(store, slug, title) {
    const p = product(store, slug);
    if (p.free) {
      return el("a", { class: "btn free", href: `${BASE}tracks/${slug}.gpx`, download: `${slug}.gpx`,
        "aria-label": `Scarica gratis il GPX di ${title}` }, "Scarica gratis");
    }
    return priceButton(p.price, p.checkout, title);
  }

  function priceButton(price, checkout, title) {
    const url = checkoutUrl(checkout);
    const label = `Acquista · ${euro.format(price)}`;
    if (!url) {
      return el("span", { class: "btn", "aria-disabled": "true", title: "Disponibile a breve" },
        `In arrivo · ${euro.format(price)}`);
    }
    return el("a", { class: "btn buy", href: url, target: "_blank", rel: "noopener",
      "aria-label": `${label}: ${title}` }, label);
  }

  // --- small route drawing for cards -----------------------------------------

  function project(points, w, h, pad) {
    const lat0 = points.reduce((s, p) => s + p[1], 0) / points.length;
    const k = Math.cos((lat0 * Math.PI) / 180);
    const xs = points.map((p) => p[0] * k), ys = points.map((p) => -p[1]);
    const x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(...ys), y1 = Math.max(...ys);
    const s = Math.min((w - 2 * pad) / (x1 - x0 || 1), (h - 2 * pad) / (y1 - y0 || 1));
    const ox = (w - (x1 - x0) * s) / 2, oy = (h - (y1 - y0) * s) / 2;
    return (p) => [ox + (p[0] * k - x0) * s, oy + (-p[1] - y0) * s];
  }

  function miniMap(ride, free) {
    const W = 320, H = 200;
    const P = project(ride.preview, W, H, 22);
    const d = ride.preview.map((p, i) => `${i ? "L" : "M"}${P(p).map((v) => v.toFixed(1)).join(",")}`).join("");
    const color = free ? C.sky : C.route;
    const svg = el("svg:svg", { viewBox: `0 0 ${W} ${H}`, role: "img", "aria-label": `Percorso di ${ride.title}` });
    svg.append(
      el("svg:path", { d, fill: "none", stroke: C.paper, "stroke-width": 9, "stroke-linecap": "round", "stroke-linejoin": "round" }),
      el("svg:path", { d, fill: "none", stroke: color, "stroke-width": 4, "stroke-linecap": "round", "stroke-linejoin": "round" }),
    );
    const [sx, sy] = P(ride.preview[0]);
    svg.append(el("svg:circle", { cx: sx, cy: sy, r: 5, fill: C.ink, stroke: C.paper, "stroke-width": 2 }));
    for (const m of ride.markers.filter((m) => m.kind === "pass")) {
      const [x, y] = P([m.lon, m.lat]);
      svg.append(el("svg:path", { d: `M${x},${y - 8}l7,11h-14z`, fill: C.ink, stroke: C.paper, "stroke-width": 1.5 }));
    }
    return svg;
  }

  // --- leaflet helpers --------------------------------------------------------

  function baseMap(node, store, opts = {}) {
    const map = L.map(node, { scrollWheelZoom: false, zoomSnap: 0.25, ...opts });
    L.tileLayer(store.mapTiles.url, { attribution: store.mapTiles.attribution, maxZoom: store.mapTiles.maxZoom }).addTo(map);
    map.attributionControl.setPrefix(false);
    // Wheel zoom only once the map has been clicked, so the page still scrolls.
    map.once("focus", () => map.scrollWheelZoom.enable());
    return map;
  }

  function passIcon() {
    return L.divIcon({
      className: "",
      html: `<svg width="18" height="16" viewBox="0 0 18 16"><path d="M9 1l8 14H1z" fill="${C.ink}" stroke="${C.paper}" stroke-width="1.6"/></svg>`,
      iconSize: [18, 16], iconAnchor: [9, 12],
    });
  }

  function routeLine(ride, color) {
    const ll = ride.preview.map((p) => [p[1], p[0]]);
    return L.layerGroup([
      L.polyline(ll, { color: C.paper, weight: 8, opacity: 0.9, interactive: false }),
      L.polyline(ll, { color, weight: 4.5, opacity: 1 }),
    ]);
  }

  // --- home -------------------------------------------------------------------

  function renderHome({ store, rides, bySlug }) {
    const grid = document.getElementById("grid");
    const cards = rides.map((r) => {
      const free = !!product(store, r.slug).free;
      const href = `${BASE}tracce/${r.slug}.html`;
      const card = el("article", { class: "card", "data-area": r.area, "data-free": free ? "1" : "0" },
        el("a", { class: "card-map", href, tabindex: "-1", "aria-hidden": "true" },
          miniMap(r, free),
          el("span", { class: `badge${free ? " is-free" : ""}` }, free ? "Gratis" : euro.format(product(store, r.slug).price))),
        el("div", { class: "card-body" },
          el("p", { class: "area" }, r.area),
          el("h3", {}, el("a", { href }, r.title)),
          el("p", { class: "sub" }, r.subtitle),
          el("dl", { class: "stats" },
            el("div", {}, el("dt", {}, "Distanza"), el("dd", {}, km(r.km))),
            el("div", {}, el("dt", {}, "Salita"), el("dd", {}, metres(r.ascent))),
            el("div", {}, el("dt", {}, "Quota"), el("dd", {}, metres(topOf(r)))),
            el("div", {}, el("dt", {}, "Guida"), el("dd", {}, duration(r.minutes)))),
          el("div", { class: "card-actions" },
            el("a", { class: "btn ghost", href }, "Dettagli"),
            buyButton(store, r.slug, r.title))));
      return card;
    });
    grid.replaceChildren(...cards);

    const chips = [...document.querySelectorAll("#filters .chip")];
    chips.forEach((chip) => chip.addEventListener("click", () => {
      chips.forEach((c) => c.setAttribute("aria-pressed", String(c === chip)));
      const f = chip.dataset.filter;
      cards.forEach((card) => {
        const show = f === "all" || (f === "free" ? card.dataset.free === "1" : card.dataset.area.includes(f));
        card.hidden = !show;
      });
    }));

    renderBundles(store, bySlug);
    renderOverview(store, rides);
  }

  // Official pass height where the ride crosses one, else the terrain model.
  function topOf(ride) {
    const passes = ride.markers.filter((m) => m.kind === "pass").map((m) => m.ele);
    return passes.length ? Math.max(...passes) : ride.maxEle;
  }

  function renderBundles(store, bySlug) {
    const host = document.getElementById("bundles");
    if (!host) return;
    host.replaceChildren(...store.bundles.map((b, i) => {
      const full = b.rides.reduce((s, slug) => s + (product(store, slug).price || 0), 0);
      const save = Math.round((1 - b.price / full) * 100);
      return el("article", { class: `bundle${i === store.bundles.length - 1 ? " featured" : ""}`, id: `pacchetto-${b.slug}` },
        el("p", { class: "eyebrow" }, `${b.rides.length} tracce`),
        el("h3", {}, b.title),
        el("p", { class: "muted", style: "margin:0" }, b.description),
        el("div", { class: "price" }, el("strong", {}, euro.format(b.price)), el("s", {}, euro.format(full))),
        el("p", { class: "save", style: "margin:0" }, `Risparmi il ${save}%`),
        el("ul", {}, b.rides.map((slug) => el("li", {},
          el("a", { href: `${BASE}tracce/${slug}.html` }, bySlug[slug] ? bySlug[slug].title : slug)))),
        priceButton(b.price, b.checkout, b.title));
    }));
  }

  function renderOverview(store, rides) {
    const node = document.getElementById("overview");
    if (!node || !window.L) return;
    const map = baseMap(node, store);
    // Leaflet needs a view before vector layers can be added.
    const bounds = L.latLngBounds(rides.flatMap((r) => r.preview.map((p) => [p[1], p[0]])));
    map.fitBounds(bounds, { padding: [24, 24] });
    for (const r of rides) {
      const free = !!product(store, r.slug).free;
      const line = routeLine(r, free ? C.sky : C.route).addTo(map);
      const href = `${BASE}tracce/${r.slug}.html`;
      line.eachLayer((l) => l.options.interactive !== false &&
        l.bindPopup(`<a href="${href}">${r.title}</a><br>${km(r.km)} · +${metres(r.ascent)}${free ? " · gratis" : ""}`));
      for (const m of r.markers.filter((m) => m.kind === "pass")) {
        L.marker([m.lat, m.lon], { icon: passIcon(), keyboard: false })
          .bindTooltip(`${m.name} · ${metres(m.ele)}`, { direction: "top", offset: [0, -10] })
          .on("click", () => (location.href = href))
          .addTo(map);
      }
    }
  }

  // --- ride page --------------------------------------------------------------

  function renderRide({ store, bySlug }) {
    const ride = bySlug[body.dataset.slug];
    if (!ride) return;
    const p = product(store, ride.slug);

    const box = document.getElementById("buybox");
    if (box) {
      box.replaceChildren(
        el("div", { class: "price" }, p.free ? "Gratis" : euro.format(p.price)),
        buyButton(store, ride.slug, ride.title),
        el("p", { class: "note" }, p.free
          ? "File GPX: traccia, percorso e waypoint dei passi."
          : "Pagamento sicuro su Gumroad, con carta o PayPal. Il GPX arriva subito per email."));
    }

    const hint = document.getElementById("bundle-hint");
    const bundle = store.bundles.find((b) => b.rides.includes(ride.slug) && b.rides.length < 6) ||
      store.bundles.find((b) => b.rides.includes(ride.slug));
    if (hint && bundle && !p.free) {
      hint.replaceChildren(el("p", { class: "callout" },
        "Fa parte del pacchetto ", el("a", { href: `${BASE}#pacchetto-${bundle.slug}` }, bundle.title),
        `: ${bundle.rides.length} tracce a ${euro.format(bundle.price)}.`));
    }

    let mover = null;
    const mapNode = document.getElementById("ride-map");
    if (mapNode && window.L) {
      const map = baseMap(mapNode, store);
      const b = ride.bbox;
      map.fitBounds([[b[1], b[0]], [b[3], b[2]]], { padding: [28, 28] });
      routeLine(ride, p.free ? C.sky : C.route).addTo(map);
      for (const m of ride.markers) {
        if (m.kind === "pass") {
          L.marker([m.lat, m.lon], { icon: passIcon(), keyboard: false }).addTo(map)
            .bindTooltip(`${m.name} · ${metres(m.ele)}`, { permanent: true, direction: "right", offset: [8, -2], className: "pass-label" });
        } else {
          L.circleMarker([m.lat, m.lon], { radius: 5, color: C.paper, weight: 2, fillColor: C.ink, fillOpacity: 1 }).addTo(map)
            .bindTooltip(m.name, { direction: "top", offset: [0, -6] });
        }
      }
      mover =L.circleMarker([ride.profile[0][3], ride.profile[0][2]],
        { radius: 7, color: "#fff", weight: 3, fillColor: C.ink, fillOpacity: 1, opacity: 0 }).addTo(map);
      mover.setStyle({ fillOpacity: 0 });
    }

    const prof = document.getElementById("profile-chart");
    if (prof) {
      drawProfile(prof, ride, mover);
      let lastW = prof.clientWidth, timer = 0;
      window.addEventListener("resize", () => {
        clearTimeout(timer);
        timer = setTimeout(() => {
          if (prof.clientWidth !== lastW) { lastW = prof.clientWidth; drawProfile(prof, ride, mover); }
        }, 150);
      });
    }
  }

  function drawProfile(host, ride, mover) {
    // Drawn at the container's real width so the type stays 12-13 px on a
    // phone instead of shrinking with a fixed viewBox.
    const W = Math.max(300, Math.round(host.clientWidth) || 1000);
    const narrow = W < 600;
    const H = narrow ? 210 : 260, L0 = narrow ? 42 : 54, R0 = narrow ? 8 : 16, T0 = 30, B0 = 34;
    const pts = ride.profile;
    const kmMax = pts[pts.length - 1][0];
    const lo = Math.floor((Math.min(...pts.map((p) => p[1])) - 80) / 250) * 250;
    const hi = Math.ceil((Math.max(...pts.map((p) => p[1]), ...ride.markers.map((m) => m.ele)) + 120) / 250) * 250;
    const X = (k) => L0 + (k / kmMax) * (W - L0 - R0);
    const Y = (e) => T0 + (1 - (e - lo) / (hi - lo)) * (H - T0 - B0);

    const svg = el("svg:svg", { viewBox: `0 0 ${W} ${H}`, role: "img",
      "aria-label": `Profilo altimetrico: ${km(ride.km)}, salita ${metres(ride.ascent)}, quota massima ${metres(topOf(ride))}` });
    const step = hi - lo > 1500 ? 500 : 250;
    for (let e = lo; e <= hi; e += step) {
      svg.append(el("svg:line", { x1: L0, x2: W - R0, y1: Y(e), y2: Y(e), stroke: C.line, "stroke-width": 1 }),
        el("svg:text", { x: L0 - 8, y: Y(e) + 4, "text-anchor": "end", "font-size": 12, fill: "#8a8170" }, `${num(e)}`));
    }
    const kStep = (narrow ? kmMax > 60 : kmMax > 80) ? (narrow && kmMax > 100 ? 40 : 20) : kmMax > 40 ? 10 : 5;
    for (let k = 0; k <= kmMax; k += kStep) {
      svg.append(el("svg:text", { x: X(k), y: H - 10, "text-anchor": "middle", "font-size": 12, fill: "#8a8170" }, `${k} km`));
    }
    const line = pts.map((p, i) => `${i ? "L" : "M"}${X(p[0]).toFixed(1)},${Y(p[1]).toFixed(1)}`).join("");
    svg.append(
      el("svg:path", { d: `${line}L${X(kmMax)},${Y(lo)}L${X(0)},${Y(lo)}Z`, fill: C.route, "fill-opacity": 0.12 }),
      el("svg:path", { d: line, fill: "none", stroke: C.route, "stroke-width": 2.5, "stroke-linejoin": "round" }));

    for (const m of ride.markers.filter((m) => m.kind === "pass")) {
      const x = X(m.km), y = Y(m.ele);
      const label = narrow ? num(m.ele) : `${m.name.toUpperCase()} ${num(m.ele)}`;
      const room = narrow ? 30 : 160;
      const anchor = x > W - room ? "end" : x < L0 + room / 2 ? "start" : "middle";
      svg.append(
        el("svg:path", { d: `M${x},${y - 6}l6,9h-12z`, fill: C.ink }),
        el("svg:text", { x, y: y - 12, "text-anchor": anchor, "font-size": 13, "font-weight": 800, fill: C.ink,
          stroke: C.paper, "stroke-width": 4, "paint-order": "stroke" }, label));
    }

    const cursor = el("svg:line", { y1: T0 - 6, y2: H - B0, stroke: C.ink, "stroke-width": 1, opacity: 0 });
    const dot = el("svg:circle", { r: 5, fill: C.ink, stroke: "#fff", "stroke-width": 2, opacity: 0 });
    const readout = el("svg:text", { x: W - R0, y: 16, "text-anchor": "end", "font-size": 13, "font-weight": 700, fill: C.ink });
    svg.append(cursor, dot, readout);

    const show = (evt) => {
      const r = svg.getBoundingClientRect();
      const x = ((evt.clientX - r.left) / r.width) * W;
      const k = Math.max(0, Math.min(kmMax, ((x - L0) / (W - L0 - R0)) * kmMax));
      let best = pts[0];
      for (const p of pts) if (Math.abs(p[0] - k) < Math.abs(best[0] - k)) best = p;
      cursor.setAttribute("x1", X(best[0])); cursor.setAttribute("x2", X(best[0]));
      dot.setAttribute("cx", X(best[0])); dot.setAttribute("cy", Y(best[1]));
      cursor.setAttribute("opacity", 0.5); dot.setAttribute("opacity", 1);
      readout.textContent = `km ${num(best[0], 1)} · ${metres(best[1])}`;
      if (mover) { mover.setLatLng([best[3], best[2]]); mover.setStyle({ opacity: 1, fillOpacity: 1 }); }
    };
    const hide = () => {
      cursor.setAttribute("opacity", 0); dot.setAttribute("opacity", 0); readout.textContent = "";
      if (mover) mover.setStyle({ opacity: 0, fillOpacity: 0 });
    };
    svg.addEventListener("pointermove", show);
    svg.addEventListener("pointerdown", show);
    svg.addEventListener("pointerleave", hide);
    host.replaceChildren(svg);
  }

  load().then((ctx) => {
    if (PAGE === "home") renderHome(ctx);
    if (PAGE === "ride") renderRide(ctx);
  }).catch((err) => {
    console.error(err);
    const grid = document.getElementById("grid");
    if (grid) grid.textContent = "Non riesco a caricare il catalogo. Ricarica la pagina tra qualche istante.";
  });
})();
